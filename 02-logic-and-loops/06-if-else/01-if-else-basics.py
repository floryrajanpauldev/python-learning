# If / Else Statements

#

# We use if/else blocks to make decisions

# in a Python program.

#

# The `if` block runs when its condition is True.

# The `else` block runs when the condition is False.

# ----------------------------------------

# Example: Checking Noise Levels

# ----------------------------------------

decibels = 20

if decibels > 89:
    print("Warning: Loud Environment!")
else:
    print("Noise levels acceptable.")

# Output:

# Noise levels acceptable.

# ----------------------------------------

# Understanding Indentation

# ----------------------------------------

#

# Indentation is very important in Python.

#

# Typically, we use 4 spaces to indent the

# code that belongs to an if/else block.

#

# The indented print() statement belongs to

# the block directly above it.

#

# The colon (:) starts the block, and indentation

# tells Python which statements belong to it.

#

# Unlike JavaScript, Python does not use curly

# braces {} to define if/else blocks.

# JavaScript example:

#

# if (age >= 18) {

# console.log("Something");

# }

#

#

# Equivalent Python example:

#

# if age >= 18:

# print("Something")

# ----------------------------------------

# Key Takeaways

# ----------------------------------------

#

# if      -> runs when the condition is True

# else    -> runs when the condition is False

# :       -> marks the beginning of a block

# Indentation -> identifies the statements in a block

#

# Python convention: use 4 spaces for indentation.
