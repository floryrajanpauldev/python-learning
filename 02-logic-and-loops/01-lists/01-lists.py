# Python Lists

#

# A list is a Python datatype used to store a collection of items.

# Lists are written inside square brackets [] with comma-separated items.

#

# Lists are similar to arrays in JavaScript.

#

# A list can contain different data types.

# ----------------------------------------

# 1. List of strings

# ----------------------------------------

fruits = ["apple", "orange", "banana"]

print(fruits)

# ----------------------------------------

# 2. List of integers

# ----------------------------------------

ratings = [8, 9, 10]

print(ratings)

# ----------------------------------------

# 3. List of floats

# ----------------------------------------

prices = [3.99, 4.99, 5.99]

print(prices)

# ----------------------------------------

# 4. A list can contain other lists

# ----------------------------------------

scores = [[2, 3], [4, 5, 6], [7, 8, 9]]

print(scores)

# ----------------------------------------

# 5. Lists can contain emojis

# ----------------------------------------

#

# Emojis are text, so they are written inside quotes.

mood = ["☀️", "❤️", "🌈"]

print(mood)

