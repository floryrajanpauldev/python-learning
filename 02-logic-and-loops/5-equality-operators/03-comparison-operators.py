# Comparison Operators

#

# Comparison operators are used to compare values

# and determine whether one value is greater than,

# smaller than, or equal to another value.

#

# Comparison operators return a Boolean value:

# True or False.

# ----------------------------------------

# 1. Greater than >

# ----------------------------------------

print(10 > 5)

# Output:

# True

print(10 > 10)

# Output:

# False

#

# 10 is not greater than 10.

# They are equal.

# ----------------------------------------

# 2. Less than <

# ----------------------------------------

print(3 < 1)

# Output:

# False

# ----------------------------------------

# 3. Greater than or equal to >=

# ----------------------------------------

print(10 >= 10)

# Output:

# True

#

# 10 is equal to 10,

# so the condition is True.

# ----------------------------------------

# 4. Less than or equal to <=

# ----------------------------------------

#

# Example:

#

# 5 <= 5

#

# This is True because 5 is equal to 5.

# ========================================

# Example: Checking Age

# ========================================

age = 20

is_adult = age >= 18

print(is_adult)

# Output:

# True

print(f"Is Old Enough: {age >= 18}")

# Output:

# Is Old Enough: True

# ----------------------------------------

# Comparison Operators and Strings

# ----------------------------------------

#

# Comparison operators can also be used

# with strings.

#

# Python compares strings alphabetically

# based on the characters.

print("banana" < "cherry")

# Output:

# True

#

# "banana" comes before "cherry"

# alphabetically.

# ----------------------------------------

# Comparison Operator Summary

# ----------------------------------------

#

# >   Greater than

# <   Less than

# >=  Greater than or equal to

# <=  Less than or equal to

#

# The result of a comparison is always

# a Boolean value:

#

# True

# False
