#statistics — Mathematical statistics functions¶

import statistics

#MEAN - statistics.mean() will give you the mean of a list of numbers
numbers = [1, 2, 3, 4, 5]
mean = statistics.mean(numbers) # this will give you the mean of the list of numbers
print(mean) # this will print the mean of the list of numbers   - 3

print(statistics.mean([100, 90]))  # this will print the mean of the list of numbers   - 95