
"""
Python Day 1 - Variables

Variables are used to store values that can be used later
in a program.

Unlike JavaScript, Python does not require keywords such as
let, const, or var when creating a variable.
"""

# Creating variables
name = "Lori"
age = 25
is_developer = True

# Displaying variable values
print(name)
print(age)
print(is_developer)


# Variables can be reassigned
age = 26

print(age)


# Python determines the data type automatically.
# We don't need to explicitly declare the type.

name = "Lori"       # str
age = 26             # int
height = 5.5         # float
is_developer = True  # bool

