
"""
Python Day 1 - Strings

A string is a sequence of characters.
Strings can be created using single or double quotes.
"""

# Creating strings
first_name = "Lori"
last_name = 'Paul'

print(first_name)
print(last_name)


# Combining strings
full_name = first_name + " " + last_name

print(full_name)

# Strings can contain spaces
greeting = "Hello, welcome to Python!"

print(greeting)
